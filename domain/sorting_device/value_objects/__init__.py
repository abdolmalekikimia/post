from __future__ import annotations

from dataclasses import dataclass
from enum import Enum
import re
import secrets
import hashlib


class DeviceType(str, Enum):
    """Sorting device types allowed in the system"""
    SORTER = "Sorter"
    SCANNER = "Scanner"
    CAMERA = "Camera"
    PRINTER = "Printer"
    CONVEYOR = "Conveyor"

    @classmethod
    def from_string(cls, value: str) -> DeviceType:
        """Convert a string to the Enum, case-insensitive"""
        for member in cls:
            if member.value.lower() == value.lower():
                return member
        raise ValueError(f"Invalid device type: {value}. Must be one of: {', '.join(m.value for m in cls)}")


