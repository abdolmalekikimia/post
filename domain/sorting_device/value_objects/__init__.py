@dataclass(frozen=True)
class DeviceId:
    """
    Unique device id - UUID v4
    
    Generated by Core, unguessable.
    """
    value: str

    def __post_init__(self) -> None:
        if not self.value or not self.value.strip():
            raise ValueError("DeviceId cannot be empty")
        
        cleaned = self.value.strip()
        uuid_pattern = re.compile(
            r'^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$',
            re.IGNORECASE
        )
        if not uuid_pattern.match(cleaned):
            raise ValueError("DeviceId must be a valid UUID v4")
        
        object.__setattr__(self, "value", cleaned.lower())

    def __str__(self) -> str:
        return self.value

    @classmethod
    def generate(cls) -> DeviceId:
        """Generate a new DeviceId"""
        import uuid
        return cls(str(uuid.uuid4()))


@dataclass(frozen=True)
class DeviceToken:
    """
    Device security token - secure random string
    
    Generated by Core during registration, never exposed in logs.
    Stored as hash in database, plain token returned only once at creation.
    """
    value: str

    def __post_init__(self) -> None:
        if not self.value or not self.value.strip():
            raise ValueError("DeviceToken cannot be empty")
        
        cleaned = self.value.strip()
        if len(cleaned) < 32:
            raise ValueError("DeviceToken must be at least 32 characters")
        
        object.__setattr__(self, "value", cleaned)

    def __str__(self) -> str:
        return self.value

    def hash(self) -> str:
        """Return the SHA-256 hash of the token for safe storage"""
        return hashlib.sha256(self.value.encode()).hexdigest()

    @classmethod
    def generate(cls) -> DeviceToken:
        """Generate a new secure DeviceToken (32 bytes = 64 hex chars)"""
        return cls(secrets.token_hex(32))

    def redacted(self) -> str:
        """Masked version for logging"""
        if len(self.value) <= 8:
            return "****"
        return self.value[:4] + "*" * (len(self.value) - 8) + self.value[-4:]


@dataclass(frozen=True)
class LogicalCode:
    """
    Logical device code - unique across the whole system
    
    Human-readable identifier, unique across system.
    Used for device lookup and operational workflows.
    """
    value: str

    def __post_init__(self) -> None:
        if not self.value or not self.value.strip():
            raise ValueError("LogicalCode cannot be empty")
        
        cleaned = self.value.strip()
        if len(cleaned) > 50:
            raise ValueError("LogicalCode too long (max 50 chars)")
        
        # Only alphanumeric, dash, underscore
        if not re.match(r'^[a-zA-Z0-9_-]+$', cleaned):
            raise ValueError("LogicalCode must contain only alphanumeric, dash, underscore")
        
        object.__setattr__(self, "value", cleaned)

    def __str__(self) -> str:
        return self.value


@dataclass(frozen=True)
class ExchangeCenterCode:
    """
    Exchange-center code - 5 digits
    
    Immutable after device creation.
    """
    value: str

    def __post_init__(self) -> None:
        if not self.value or not self.value.strip():
            raise ValueError("ExchangeCenterCode cannot be empty")
        
        cleaned = self.value.strip()
        if not cleaned.isdigit():
            raise ValueError("ExchangeCenterCode must contain only digits")
        
        if len(cleaned) != 5:
            raise ValueError("ExchangeCenterCode must be exactly 5 digits")
        
        object.__setattr__(self, "value", cleaned)

    def __str__(self) -> str:
        return self.value


